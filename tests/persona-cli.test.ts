import {test} from 'node:test';
import assert from 'node:assert/strict';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {mkdtemp,readFile,stat,rename} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const exec=promisify(execFile);
test('persona CLI writes auditable fake artifacts and can reanalyze them without inference',async()=>{
 let root=join(await mkdtemp(join(tmpdir(),'jev-persona-cli-')),'experiment');
 await exec(process.execPath,['--import','tsx','runner/persona-experiment.ts','--fake','--baseline-only','--repeat','1','--out',root],{timeout:60000});
 const manifest=JSON.parse(await readFile(join(root,'manifest.json'),'utf8'));
 assert.ok(manifest.sourceHashes['jev/persona.ts']);assert.ok(manifest.sourceHashes['runner/persona-report.ts']);
 assert.equal(manifest.sourceHash.length,64);
 let comparison=JSON.parse(await readFile(join(root,'comparison.json'),'utf8'));
 assert.equal(comparison.evidence,'PLUMBING_ONLY');assert.equal(comparison.complete,true);
 assert.equal(comparison.conditions[0].objectiveSuccesses,1);
 const event=JSON.parse((await readFile(join(root,'baseline-1','events.jsonl'),'utf8')).split('\n')[0]);
 assert.equal(event.condition,'baseline');assert.equal(event.state.exploration.persona,undefined);
 assert.ok(!('oracle' in event.state.exploration.charter));assert.ok(event.outcome.screenshot);
 assert.ok((await stat(join(root,'baseline-1','trace.zip'))).size>100);
 assert.ok((await readFile(join(root,'comparison.html'),'utf8')).includes('FAKE'));
 const moved=root+'-moved';await rename(root,moved);root=moved;
 await exec(process.execPath,['--import','tsx','runner/persona-compare.ts',root],{timeout:60000});
 comparison=JSON.parse(await readFile(join(root,'comparison.json'),'utf8'));
 assert.equal(comparison.evidence,'PLUMBING_ONLY');assert.equal(comparison.runs.length,1);
 assert.ok(!(await readFile(join(root,'index.html'),'utf8')).includes('../experiment/baseline-1'));
 await assert.rejects(exec(process.execPath,['--import','tsx','runner/persona-experiment.ts','--fake','--repeat','0']),/repeat must be/);
});
